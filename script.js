function initProjects() {
  document.querySelectorAll(".project-card").forEach((card) => card.querySelector(".project-open").addEventListener("click", () => openProject(card.dataset.project, card.querySelector(".project-open"))));
  closeButton.addEventListener("click", closeProject);
  dialog.addEventListener("cancel", (event) => { event.preventDefault(); closeProject(); });
  const dialogBar = dialog.querySelector(".dialog-progress span");
  dialog.addEventListener("scroll", () => { const max = dialog.scrollHeight - dialog.clientHeight; dialogBar.style.transform = `scaleX(${max > 0 ? dialog.scrollTop / max : 0})`; }, { passive: true });
}

function initSlider() {
  const slider = document.querySelector(".proof-slider");
  const amount = () => Math.min(458, innerWidth * .82);
  document.querySelectorAll("[data-slide]").forEach((button) => button.addEventListener("click", () => slider.scrollBy({left:(button.dataset.slide === "next" ? 1 : -1) * amount(),behavior:reduceMotion ? "auto" : "smooth"})));
  slider.addEventListener("keydown", (event) => { if (event.key === "ArrowRight") slider.scrollBy({left:amount(),behavior:"smooth"}); if (event.key === "ArrowLeft") slider.scrollBy({left:-amount(),behavior:"smooth"}); });
}

function initContactForm() {
  const form = document.querySelector("#contact-form");
  const status = document.querySelector("#form-status");
  const submitButton = form.querySelector("button[type='submit']");
  const receiver = String.fromCharCode(112,121,57,48,57,56,49,56,64,103,109,97,105,108,46,99,111,109);
  form.action = `https://formsubmit.co/ajax/${receiver}`;
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    if (!form.reportValidity()) return;
    submitButton.disabled = true;
    submitButton.textContent = "Sending…";
    status.textContent = "Sending your enquiry…";
    try {
      const response = await fetch(form.action, { method: "POST", body: new FormData(form), headers: { Accept: "application/json" } });
      if (!response.ok) throw new Error("Submission failed");
      form.reset();
      status.textContent = "Thank you — your enquiry has been sent successfully.";
    } catch {
      status.textContent = "The direct send could not complete. Your email app will open as a backup.";
      const data = new FormData(form);
      const subject = encodeURIComponent(`Portfolio enquiry — ${data.get("project")}`);
      const body = encodeURIComponent(`Name: ${data.get("name")}\nEmail: ${data.get("email")}\n\n${data.get("message")}`);
      window.location.href = `mailto:${receiver}?subject=${subject}&body=${body}`;
    } finally {
      submitButton.disabled = false;
      submitButton.innerHTML = `Send enquiry <span aria-hidden="true">↗</span>`;
    }
  });
}

