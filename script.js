const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const finePointer = window.matchMedia("(pointer: fine)").matches;
let lenis = null;

function splitKineticType() {
  document.querySelectorAll("[data-kinetic]").forEach((line, lineIndex) => {
    const text = line.textContent;
    line.textContent = "";
    [...text].forEach((character, charIndex) => {
      const span = document.createElement("span");
      span.className = "char";
      span.textContent = character === " " ? "\u00a0" : character;
      span.style.setProperty("--char-delay", `${0.04 + lineIndex * 0.11 + charIndex * 0.012}s`);
      line.appendChild(span);
    });
  });
}

function initSmoothScroll() {
  if (reduceMotion) return;
  const start = () => {
    if (!window.Lenis || lenis) return;
    lenis = new window.Lenis({ duration: 1.08, smoothWheel: true, wheelMultiplier: .9, touchMultiplier: 1.1 });
    const raf = (time) => { lenis.raf(time); requestAnimationFrame(raf); };
    requestAnimationFrame(raf);
  };
  if (window.Lenis) { start(); return; }
  const script = document.createElement("script");
  script.src = "https://cdn.jsdelivr.net/npm/lenis@1.1.20/dist/lenis.min.js";
  script.async = true;
  script.onload = start;
  document.head.appendChild(script);
}

function initMagnetic() {
  if (!finePointer || reduceMotion) return;
  document.querySelectorAll(".magnetic").forEach((element) => {
    element.addEventListener("pointermove", (event) => {
      const rect = element.getBoundingClientRect();
      const x = event.clientX - rect.left - rect.width / 2;
      const y = event.clientY - rect.top - rect.height / 2;
      element.style.transform = `translate(${x * .16}px,${y * .22}px)`;
    });
    element.addEventListener("pointerleave", () => { element.style.transform = ""; });
  });
}

function initTilt(root = document) {
  if (!finePointer || reduceMotion) return;
  root.querySelectorAll("[data-tilt]").forEach((element) => {
    if (element.dataset.tiltReady) return;
    element.dataset.tiltReady = "true";
    element.addEventListener("pointermove", (event) => {
      const rect = element.getBoundingClientRect();
      const px = (event.clientX - rect.left) / rect.width - .5;
      const py = (event.clientY - rect.top) / rect.height - .5;
      const intensity = element.classList.contains("tilt-card") ? 7 : 10;
      element.style.transform = `rotateX(${-py * intensity}deg) rotateY(${px * intensity}deg) translateZ(0)`;
      element.querySelectorAll("[data-depth]").forEach((child) => {
        const depth = Number(child.dataset.depth || 1);
        child.style.translate = `${px * 18 * depth}px ${py * 18 * depth}px`;
      });
    });
    element.addEventListener("pointerleave", () => {
      element.style.transform = "";
      element.querySelectorAll("[data-depth]").forEach((child) => { child.style.translate = ""; });
    });
  });
}

function initScrollEffects() {
  const progress = document.querySelector(".scroll-progress span");
  const parallaxItems = [...document.querySelectorAll("[data-parallax]")];
  let ticking = false;
  const update = () => {
    const max = document.documentElement.scrollHeight - innerHeight;
    progress.style.transform = `scaleX(${max > 0 ? scrollY / max : 0})`;
    if (!reduceMotion) parallaxItems.forEach((item) => { item.style.transform = `translate3d(0,${scrollY * Number(item.dataset.parallax)}px,0)`; });
    ticking = false;
  };
  addEventListener("scroll", () => { if (!ticking) { ticking = true; requestAnimationFrame(update); } }, { passive: true });
  update();

  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => { if (entry.isIntersecting) { entry.target.classList.add("is-visible"); revealObserver.unobserve(entry.target); } });
  }, { threshold: .12, rootMargin: "0px 0px -6%" });
  document.querySelectorAll(".reveal-on-scroll").forEach((element) => revealObserver.observe(element));
}

function initCounters() {
  const counters = [...document.querySelectorAll("[data-count]")];
  if (reduceMotion) { counters.forEach((el) => { el.textContent = `${el.dataset.count}${el.dataset.suffix}`; }); return; }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      const element = entry.target, target = Number(element.dataset.count), suffix = element.dataset.suffix, start = performance.now();
      const tick = (now) => { const p = Math.min((now - start) / 1100, 1); element.textContent = `${Math.round(target * (1 - Math.pow(1 - p, 3)))}${suffix}`; if (p < 1) requestAnimationFrame(tick); };
      requestAnimationFrame(tick); observer.unobserve(element);
    });
  }, { threshold: .7 });
  counters.forEach((counter) => observer.observe(counter));
}

function initFilters() {
  const buttons = [...document.querySelectorAll(".filter-button")];
  const cards = [...document.querySelectorAll(".project-card")];
  const applyFilter = (filter) => {
    cards.forEach((card) => {
      const matches = filter === "all" || card.dataset.category.split(" ").includes(filter);
      card.classList.toggle("is-hidden", !matches);
      if (matches && !reduceMotion) card.animate([{opacity:0,transform:"translateY(24px) scale(.97)"},{opacity:1,transform:"none"}],{duration:520,easing:"cubic-bezier(.2,.75,.25,1)"});
    });
  };
  buttons.forEach((button) => button.addEventListener("click", () => {
    buttons.forEach((item) => { const active = item === button; item.classList.toggle("is-active", active); item.setAttribute("aria-pressed", String(active)); });
    const update = () => applyFilter(button.dataset.filter);
    if (document.startViewTransition && !reduceMotion) document.startViewTransition(update); else update();
  }));
}

